package com.kuberbassi.savewave.ui

import android.annotation.SuppressLint
import android.webkit.CookieManager
import android.webkit.WebView
import android.webkit.WebViewClient
import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import androidx.compose.ui.viewinterop.AndroidView
import androidx.compose.ui.window.Dialog
import androidx.compose.ui.window.DialogProperties
import com.kuberbassi.savewave.ui.theme.BrandRed
import com.kuberbassi.savewave.ui.theme.PanelDark
import java.io.File

@SuppressLint("SetJavaScriptEnabled")
@Composable
fun InstagramAuthDialog(
    cookieFile: File,
    onSuccess: () -> Unit,
    onDismiss: () -> Unit,
) {
    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false),
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth(0.94f)
                .fillMaxHeight(0.84f)
                .background(PanelDark)
                .border(2.dp, BrandRed)
        ) {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .background(BrandRed)
                    .padding(horizontal = 14.dp, vertical = 10.dp),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween,
            ) {
                Text(
                    text = "INSTAGRAM LOGIN",
                    color = Color.White,
                    fontFamily = FontFamily.Monospace,
                    fontWeight = FontWeight.Bold,
                    fontSize = 12.sp,
                )
                TextButton(onClick = onDismiss) {
                    Text(
                        text = "CLOSE",
                        color = Color.White,
                        fontFamily = FontFamily.Monospace,
                        fontWeight = FontWeight.Bold,
                        fontSize = 11.sp,
                    )
                }
            }

            AndroidView(
                modifier = Modifier.fillMaxSize(),
                factory = { ctx ->
                    WebView(ctx).apply {
                        settings.javaScriptEnabled = true
                        settings.domStorageEnabled = true
                        CookieManager.getInstance().setAcceptCookie(true)
                        CookieManager.getInstance().setAcceptThirdPartyCookies(this, true)
                        webViewClient = object : WebViewClient() {
                            override fun onPageFinished(view: WebView?, url: String?) {
                                super.onPageFinished(view, url)
                                val rawCookies = CookieManager.getInstance()
                                    .getCookie("https://www.instagram.com/") ?: return
                                val pairs = rawCookies.split(";")
                                    .mapNotNull { entry ->
                                        val idx = entry.indexOf('=')
                                        if (idx > 0) {
                                            entry.substring(0, idx).trim() to entry.substring(idx + 1).trim()
                                        } else null
                                    }
                                if (pairs.any { it.first == "sessionid" && it.second.isNotBlank() }) {
                                    val expires = (System.currentTimeMillis() / 1000L) + 86400L * 365L
                                    val lines = buildString {
                                        appendLine("# Netscape HTTP Cookie File")
                                        appendLine("# Generated by Savewave")
                                        for ((k, v) in pairs) {
                                            appendLine(".instagram.com\tTRUE\t/\tTRUE\t$expires\t$k\t$v")
                                        }
                                    }
                                    cookieFile.writeText(lines)
                                    onSuccess()
                                }
                            }
                        }
                        loadUrl("https://www.instagram.com/accounts/login/")
                    }
                },
            )
        }
    }
}
