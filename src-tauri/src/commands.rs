use crate::sidecar::{
    check_engine_status, instagram_cookie_path, resolve_media_with_sidecar, start_download_job,
    JobStore,
};
use savewave_core::models::{
    DownloadProgress, DownloadRequest, DownloadState, EngineStatus, MediaMode,
    PlatformCapabilities, PlatformType, ReleaseInfo, ResolvedMedia,
};
use savewave_core::updater::{fetch_release_info, is_trusted_external_url, verify_sha256};
use std::time::Duration;
use tauri::{AppHandle, Manager, State, WebviewUrl, WebviewWindowBuilder};
use tauri_plugin_opener::OpenerExt;

pub struct AppState {
    pub jobs: JobStore,
}

#[tauri::command]
pub fn get_capabilities() -> PlatformCapabilities {
    PlatformCapabilities::default_native(PlatformType::Desktop)
}

#[tauri::command]
pub async fn get_engine_status() -> EngineStatus {
    check_engine_status().await
}

#[tauri::command]
pub async fn get_release_info() -> Option<ReleaseInfo> {
    fetch_release_info(PlatformType::Desktop).await
}

#[tauri::command]
pub async fn resolve_media(url: String, mode: Option<MediaMode>) -> Result<ResolvedMedia, String> {
    resolve_media_with_sidecar(&url, mode.unwrap_or(MediaMode::Video))
        .await
        .map_err(|e| format!("{}:{}", e.code().as_str(), e.message()))
}

#[tauri::command]
pub async fn download_media(
    state: State<'_, AppState>,
    request: DownloadRequest,
) -> Result<DownloadProgress, String> {
    start_download_job(state.jobs.clone(), request)
        .await
        .map_err(|e| format!("{}:{}", e.code().as_str(), e.message()))
}

#[tauri::command]
pub async fn get_download_progress(
    state: State<'_, AppState>,
    job_id: String,
) -> Result<DownloadProgress, String> {
    let guard = state.jobs.read().await;
    guard
        .get(&job_id)
        .map(|j| j.progress.clone())
        .ok_or_else(|| "DOWNLOAD_NOT_FOUND".to_string())
}

#[tauri::command]
pub async fn cancel_download(
    state: State<'_, AppState>,
    job_id: String,
) -> Result<(), String> {
    let mut guard = state.jobs.write().await;
    let job = guard
        .get_mut(&job_id)
        .ok_or_else(|| "DOWNLOAD_NOT_FOUND".to_string())?;
    job.progress.state = DownloadState::Cancelled;
    if let Some(mut child) = job.child.take() {
        let _ = child.kill().await;
    }
    let temp_dir = job.temp_dir.clone();
    drop(guard);
    let _ = tokio::fs::remove_dir_all(temp_dir).await;
    Ok(())
}

#[tauri::command]
pub fn open_external(app: AppHandle, url: String) -> Result<(), String> {
    if !is_trusted_external_url(&url) {
        return Err("EXTERNAL_URL_REJECTED".to_string());
    }
    app.opener()
        .open_url(&url, None::<&str>)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub fn open_downloads_folder(app: AppHandle) -> Result<(), String> {
    let dir = dirs::download_dir().ok_or_else(|| "Downloads folder unavailable".to_string())?;
    app.opener()
        .open_path(dir.to_string_lossy().as_ref(), None::<&str>)
        .map_err(|e| e.to_string())
}

#[tauri::command]
pub async fn authenticate_instagram(app: AppHandle) -> Result<bool, String> {
    let login_url: url::Url = "https://www.instagram.com/accounts/login/"
        .parse()
        .map_err(|e: url::ParseError| e.to_string())?;
    let ig_origin: url::Url = "https://www.instagram.com/"
        .parse()
        .map_err(|e: url::ParseError| e.to_string())?;

    if let Some(existing) = app.get_webview_window("instagram-auth") {
        let _ = existing.close();
    }

    let window = WebviewWindowBuilder::new(&app, "instagram-auth", WebviewUrl::External(login_url))
        .title("Log in to Instagram — Savewave")
        .inner_size(480.0, 700.0)
        .build()
        .map_err(|e| e.to_string())?;

    // Poll cookies until Instagram sets `sessionid` or the user closes the window
    for _ in 0..375 {
        tokio::time::sleep(Duration::from_millis(800)).await;
        if app.get_webview_window("instagram-auth").is_none() {
            return Ok(false);
        }
        if let Ok(cookies) = window.cookies_for_url(ig_origin.clone()) {
            let has_session = cookies
                .iter()
                .any(|c| c.name() == "sessionid" && !c.value().is_empty());
            if has_session {
                let mut lines = vec![
                    "# Netscape HTTP Cookie File".to_string(),
                    "# Generated by Savewave. Do not edit.".to_string(),
                    String::new(),
                ];
                let fallback_exp = std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH)
                    .map(|d| d.as_secs() + 86400 * 365)
                    .unwrap_or(2_000_000_000);

                for c in &cookies {
                    let raw_domain = c.domain().unwrap_or("instagram.com");
                    let domain = if raw_domain.starts_with('.') {
                        raw_domain.to_string()
                    } else {
                        format!(".{raw_domain}")
                    };
                    let flag = if domain.starts_with('.') { "TRUE" } else { "FALSE" };
                    let path = c.path().unwrap_or("/");
                    let secure = if c.secure().unwrap_or(true) { "TRUE" } else { "FALSE" };
                    lines.push(format!(
                        "{domain}\t{flag}\t{path}\t{secure}\t{fallback_exp}\t{}\t{}",
                        c.name(),
                        c.value()
                    ));
                }

                let cookie_file = instagram_cookie_path();
                if let Some(parent) = cookie_file.parent() {
                    let _ = tokio::fs::create_dir_all(parent).await;
                }
                tokio::fs::write(&cookie_file, format!("{}\n", lines.join("\n")))
                    .await
                    .map_err(|e| e.to_string())?;
                let _ = window.close();
                return Ok(true);
            }
        }
    }

    let _ = window.close();
    Ok(false)
}

#[tauri::command]
pub async fn install_windows_update(app: AppHandle) -> Result<bool, String> {
    let release = fetch_release_info(PlatformType::Desktop)
        .await
        .ok_or_else(|| "Update manifest is unavailable.".to_string())?;
    if !release.update_available {
        return Ok(false);
    }
    if !is_trusted_external_url(&release.download_url) {
        return Err("Untrusted update download URL.".to_string());
    }

    let client = reqwest::Client::builder()
        .timeout(Duration::from_secs(120))
        .build()
        .map_err(|e| e.to_string())?;

    let bytes = client
        .get(&release.download_url)
        .send()
        .await
        .map_err(|e| e.to_string())?
        .error_for_status()
        .map_err(|e| e.to_string())?
        .bytes()
        .await
        .map_err(|e| e.to_string())?;

    // Verify SHA-256 against companion .sha256 release asset when published
    let sha_url = format!("{}.sha256", release.download_url);
    if let Ok(resp) = client.get(&sha_url).send().await {
        if resp.status().is_success() {
            if let Ok(text) = resp.text().await {
                let expected = text.split_whitespace().next().unwrap_or_default();
                if expected.len() == 64 && !verify_sha256(&bytes, expected) {
                    return Err("Update checksum verification failed.".to_string());
                }
            }
        }
    }

    let installer_path = std::env::temp_dir().join(format!("Savewave_{}_x64-setup.exe", release.version));
    tokio::fs::write(&installer_path, &bytes)
        .await
        .map_err(|e| e.to_string())?;

    std::process::Command::new(&installer_path)
        .spawn()
        .map_err(|e| e.to_string())?;

    app.exit(0);
    Ok(true)
}
